"""Regenerate demos/switcher_data.py: every open app's icon, FRC-encoded once
per carousel size tier.

    python gen_switcher.py [--apps 8] [--png a.png b.png ...]
    python deploy.py switch

Unlike gen_appicons.py (which bakes one fixed screen), this emits *movable*
blocks: each icon is encoded at ox=0 on its tier's page row and stored as
`size` bytes per page.  carousel.py then blits a block to any column with a
byte-slice copy, which is what makes the scroll animation affordable on-device.

The dither pattern is baked at x=0, so an icon drawn at a column that is not a
multiple of 4 gets its Bayer phase shifted.  That is invisible (it is noise
either way) and it buys per-pixel-free positioning.
"""
import _paths
import os, sys, tempfile
from PIL import Image
import appscan, gfx, frc, carousel

MAX_APPS = 8            # keep the emitted module small enough to parse on-device


def block(im, size, page0, n=4):
    """PIL image -> tuple of `n` page-aligned blocks (size bytes per page)."""
    pages = size >> 3
    fbs = frc.encode_image(im, n=n, size=(size, size), ox=0, oy=page0 * 8)
    out = []
    for fb in fbs:
        b = bytearray(pages * size)
        for r in range(pages):
            o = (page0 + r) * gfx.W
            b[r * size:(r + 1) * size] = fb[o:o + size]
        out.append(bytes(b))
    return tuple(out)


def encode_app(png, n=4):
    im = Image.open(png)
    return tuple(block(im, size, page0, n) for size, page0 in carousel.TIERS)


def emit(path, names, icons):
    # ascii only: bytes reprs are escaped, and CircuitPython reads plain ascii
    with open(path, 'w', encoding='ascii') as f:
        f.write('"""App icons for the switcher carousel, FRC-encoded per size '
                'tier.\n\nICONS[app][tier][plane] -> page-aligned block, tiers '
                'matching carousel.TIERS %r.\nGenerated by '
                'host/gen_switcher.py - do not edit.\n"""\n' % (carousel.TIERS,))
        f.write('APPS = (\n')
        for nm in names:
            f.write('    %s,\n' % ascii(nm))     # escapes any non-ascii name
        f.write(')\n\nICONS = (\n')
        for app in icons:
            f.write('  (\n')
            for tier in app:
                f.write('    (\n')
                for plane in tier:
                    f.write('      %r,\n' % plane)
                f.write('    ),\n')
            f.write('  ),\n')
        f.write(')\n')


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    limit = MAX_APPS
    pngs = []
    it = iter(argv)
    for a in it:
        if a == '--apps':
            limit = int(next(it))
        elif a == '--png':
            pngs = list(it)
        else:
            sys.exit(__doc__)

    if pngs:
        apps = [(os.path.splitext(os.path.basename(p))[0], p) for p in pngs]
    else:
        td = tempfile.mkdtemp()
        apps = appscan.open_app_icons(td)
        if not apps:
            sys.exit('no app icons found')
    apps = apps[:limit]

    names = tuple(n.upper() for n, _ in apps)
    icons = [encode_app(p) for _, p in apps]
    out = os.path.normpath(os.path.join(here, '..', 'demos', 'switcher_data.py'))
    emit(out, names, icons)
    print('wrote %s: %d apps, tiers %r, %d bytes of icon data (%.0f kB module)'
          % (out, len(apps), carousel.TIERS,
             sum(len(p) for a in icons for t in a for p in t),
             os.path.getsize(out) / 1024.0))


if __name__ == '__main__':
    main(sys.argv[1:])
