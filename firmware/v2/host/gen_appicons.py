"""Regenerate demos/appicons.py from the apps currently open on this PC.

Enumerates processes with visible windows (appscan.py), lays their icons out in
a grid, and FRC-encodes the screen (frc.py).  Run it any time; then
`python deploy.py icons` to see it on the device.

This bakes one fixed screen.  For the scrollable app switcher, whose icons have
to move, see gen_switcher.py.
"""
import _paths
import os, sys, tempfile
from PIL import Image
import appscan, gfx, frc

ICON = 30


def layout(n):
    """-> list of rows, each a list of (x, y) top-left positions."""
    per_row = (n + 1) // 2 if n > 4 else n
    rows = [list(range(per_row)), list(range(per_row, n))] if n > 4 else [list(range(n))]
    ytop = (gfx.H - len(rows) * ICON - (len(rows) - 1) * 2) // 2
    pos = []
    for r, row in enumerate(rows):
        gap = (gfx.W - len(row) * ICON) // (len(row) + 1)
        for c, _ in enumerate(row):
            pos.append((gap + c * (ICON + gap), ytop + r * (ICON + 2)))
    return pos


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    with tempfile.TemporaryDirectory() as td:
        icons = appscan.open_app_icons(td)
        if not icons:
            sys.exit('no app icons found')
        icons = icons[:8]
        planes = [gfx.new() for _ in range(4)]
        for (name, png), (x, y) in zip(icons, layout(len(icons))):
            frc.encode_image(Image.open(png), n=4, size=(ICON, ICON),
                             ox=x, oy=y, planes=planes)
    out = os.path.normpath(os.path.join(here, '..', 'demos', 'appicons.py'))
    frc.emit_module(out, planes,
                    doc='Open-app icons as 4-plane FRC planes.  '
                        'Generated by host/gen_appicons.py.')
    frc.avg_image(planes).save(os.path.join(here, 'appicons_preview.png'))
    print('wrote %s (%d apps) + appicons_preview.png' % (out, len(icons)))
