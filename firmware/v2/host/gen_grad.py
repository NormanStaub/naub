"""Regenerate demos/graygrad.py: horizontal-gradient planes for demo_gray_modes.

Three variants, white (left) -> black (right), y=16..63:
  P1  static Bayer dither (1 plane, flicker-free)   } all share the frc.py
  P4  4-plane FRC (the user-picked recipe)          } mapping; n varies
  P6  6-plane FRC (smoothest, slight shimmer)
"""
import _paths
import os
from PIL import Image
import gfx, frc

TOP = 16
INK = [[x / 127.0 for x in range(gfx.W)] for _ in range(gfx.H - TOP)]

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    out = ['"""Precomputed gradient bitplanes.  Generated by host/gen_grad.py."""']
    canvas = Image.new('L', (gfx.W * 4, (gfx.H * 4 + 10) * 3), 128)
    for row, (name, n) in enumerate((("P1", 1), ("P4", 4), ("P6", 6))):
        planes = frc.encode(INK, n=n, oy=TOP)
        out.append("%s = (" % name)
        for fb in planes:
            out.append("    %r," % bytes(fb))
        out.append(")")
        canvas.paste(frc.avg_image(planes, scale=4),
                     (0, row * (gfx.H * 4 + 10)))
        print(name, n, 'planes')
    path = os.path.normpath(os.path.join(here, '..', 'demos', 'graygrad.py'))
    with open(path, 'w') as f:
        f.write("\n".join(out) + "\n")
    canvas.save(os.path.join(here, 'grad_preview.png'))
    print('wrote %s + grad_preview.png' % path)
