"""Bake a QR code PNG into a device module.

    python gen_qr.py [--png ../../naub_qr-code.png] [--out ../device/qrdata.py]

The source PNG is already one pixel per QR module with its quiet zone included,
which is the only form worth having: at 128x64 there is no room to scale a code
up, so the panel draws it at 1 px per module and the PNG's own grid is the grid.
A generator that had to *find* the module pitch would be guessing.

It verifies what it is baking.  A QR code is opaque -- you cannot read one by
looking at the bytes -- so shipping the wrong URL to hardware is a mistake you
would only find with a phone.  If `pyzbar` is installed the code is decoded and
compared against the URL this writes into the module; if it is not, the check is
skipped with a warning rather than silently passing.
"""
import os
import sys

from PIL import Image

import _paths                                    # noqa: F401  (device/ on path)

HERE = os.path.dirname(os.path.abspath(__file__))
PNG = os.path.normpath(os.path.join(HERE, '..', '..', 'naub_qr-code.png'))
OUT = os.path.normpath(os.path.join(HERE, '..', 'device', 'qrdata.py'))
URL = 'https://github.com/NormanStaub/naub'

HEAD = '''"""%(url)s as a QR code, one bit per module.

GENERATED by host/gen_qr.py from %(png)s -- do not edit.

`ROWS[y] >> x & 1` is the module at (x, y), 1 meaning dark.  %(n)d a side, which
is a version-3 code (29) plus the 4-module quiet zone the spec asks for on every
edge.  The quiet zone is part of the data deliberately: it is what makes the
code scannable against the panel's own lit background, and leaving it to the
drawing code would make it something a later layout change could quietly eat.

An int per row rather than packed bytes because %(n)d bits stays inside
MicroPython's 63-bit small-int range, so indexing a module allocates nothing.
"""
URL = %(urlrepr)s
N = %(n)d
ROWS = (
'''


def load(png):
    """-> (n, rows) with rows[y] a bitmask, LSB = x 0.  Dark is a set bit."""
    im = Image.open(png).convert('L')
    w, h = im.size
    if w != h:
        raise SystemExit('not square: %dx%d -- expected a bare QR grid' % (w, h))
    px = im.load()
    rows = []
    for y in range(h):
        v = 0
        for x in range(w):
            if px[x, y] < 128:                   # dark module
                v |= 1 << x
        rows.append(v)
    return w, rows


def verify(png, url):
    """Decode the PNG and check it says what we are about to claim it says."""
    try:
        from pyzbar.pyzbar import decode
    except ImportError:
        print('  ! pyzbar not installed -- CANNOT verify the code decodes to')
        print('    %s.  pip install pyzbar to check.' % url)
        return None
    im = Image.open(png).convert('L')
    big = im.resize((im.width * 8, im.height * 8), Image.NEAREST)
    got = [d.data.decode() for d in decode(big)]
    if not got:
        raise SystemExit('pyzbar could not decode %s at all' % png)
    if got[0] != url:
        raise SystemExit('QR decodes to %r, not %r' % (got[0], url))
    print('  verified: decodes to %s' % got[0])
    return got[0]


def main(argv):
    png, out, url = PNG, OUT, URL
    for i, a in enumerate(argv):
        if a == '--png':
            png = argv[i + 1]
        elif a == '--out':
            out = argv[i + 1]
        elif a == '--url':
            url = argv[i + 1]
    print('reading %s' % png)
    verify(png, url)
    n, rows = load(png)
    dark = sum(bin(r).count('1') for r in rows)
    print('  %dx%d modules, %d dark' % (n, n, dark))
    body = HEAD % {'url': url, 'png': os.path.basename(png), 'n': n,
                   'urlrepr': repr(url)}
    body += ''.join('    0x%09X,\n' % r for r in rows)
    body += ')\n'
    with open(out, 'w', newline='\n') as f:
        f.write(body)
    print('wrote %s (%d bytes)' % (out, len(body)))


if __name__ == '__main__':
    main(sys.argv[1:])
